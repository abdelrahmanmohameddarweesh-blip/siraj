"""Imports the morning and evening adhkar verbatim from the Hisn al-Muslim API (hisnmuslim.com),
chapter 27 «أذكار الصباح والمساء». Texts and repeat counts are copied exactly; nothing is typed by hand.
Run: python3 scripts/import-athkar.py"""
import json, urllib.request, datetime, pathlib
URL = 'https://www.hisnmuslim.com/api/ar/27.json'
raw = urllib.request.urlopen(urllib.request.Request(URL, headers={'User-Agent': 'Sirag/1.0'}), timeout=30).read().decode('utf-8-sig')
data = json.loads(raw)
title = list(data.keys())[0]
items = []
for it in data[title]:
    items.append({
        'id': int(it['ID']),
        'text': it['ARABIC_TEXT'].strip(),
        'repeat': int(it.get('REPEAT') or 1),
        'audio': (it.get('AUDIO') or '').replace('http://', 'https://'),
    })
out = pathlib.Path('src/athkar/athkarData.ts')
out.write_text(
    '// Generated by scripts/import-athkar.py. Do not edit by hand.\n'
    f'// Source: {URL} (Hisn al-Muslim, chapter 27: {title}), imported {datetime.date.today().isoformat()}.\n'
    '// The same list is read morning and evening; bracketed notes inside a text give the evening wording.\n'
    "export const ATHKAR_SOURCE = { url: 'https://www.hisnmuslim.com', chapter: " + json.dumps(title, ensure_ascii=False) + ", importedAt: '" + datetime.date.today().isoformat() + "' };\n"
    'export type Dhikr = { id: number; text: string; repeat: number; audio: string };\n'
    'export const ATHKAR: Dhikr[] = ' + json.dumps(items, ensure_ascii=False, indent=1) + ';\n')
print('wrote', out, len(items), 'items', 'total repeats', sum(i['repeat'] for i in items))
